#!/usr/bin/env python3
"""Build key-free frontend sample data through the installed library's public API."""
import copy
import json
from pathlib import Path
from urllib.parse import quote
from maple_library import CharacterSheet, Document, Source

ROOT = Path(__file__).resolve().parents[1]
CASES = json.loads((ROOT / 'fixtures/cases/presentation-v1.json').read_text())


def icon(kind, color):
    # Original geometric demo artwork; no game assets are redistributed.
    drawings = {
        'weapon': '<path d="M28 43 46 9 53 17 35 49Z" fill="#e3f7ff" stroke="#68b9ed" stroke-width="3"/><path d="m20 43 18 10 4-7-18-10Z" fill="#e8bf63"/><path d="m27 47-9 13 6 3 9-13Z" fill="#816a42"/><path d="m44 18-6 16" stroke="white" stroke-width="3"/>',
        'ring': '<ellipse cx="36" cy="43" rx="17" ry="18" fill="none" stroke="#eccb76" stroke-width="8"/><path d="m36 12 13 12-13 14-13-14Z" fill="#a89bf6" stroke="#eee5ff" stroke-width="3"/>',
        'symbol': '<path d="m36 8 23 27-23 28L13 35Z" fill="COLOR" stroke="#e5f7ff" stroke-width="3"/><path d="m36 8 7 27-7 28-7-28Z" fill="#ffffff" opacity=".45"/><path d="m13 35 23 6 23-6" fill="none" stroke="#fff" opacity=".65" stroke-width="2"/>',
    }
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 72 72"><rect x="1" y="1" width="70" height="70" rx="18" fill="#eff5fa"/>' + drawings[kind].replace('COLOR', color) + '</svg>'
    return 'data:image/svg+xml;charset=utf-8,' + quote(svg)


def build():
    equipment_case = next(case for case in CASES if case['id'] == 'equipment-tooltip')
    weapon = copy.deepcopy(equipment_case['raw']['item_equipment'][0])
    weapon.update(item_name='샘플 튜너', item_icon=icon('weapon', ''),
                  potential_option_2='공격력 +13%', potential_option_3='공격력 +13%',
                  additional_potential_option_grade='레전드리', additional_potential_option_1='공격력 +13%',
                  additional_potential_option_2='공격력 +10%', additional_potential_option_3='공격력 +10%',
                  soul_name='위대한 샘플 소울', soul_potential_option_2='공격력 +6%', soul_potential_option_3='공격력 +6%')
    weapon['item_total_option'].update(dex='349', all_stat='6', max_hp='255', max_mp='255', damage='6', ignore_monster_armor='20')
    weapon['item_total_option'].pop('speed')
    weapon['item_base_option'].update(dex='190', all_stat='0', max_hp='0', max_mp='0', ignore_monster_armor='20', damage='0')
    weapon['item_starforce_option'].update(dex='159', max_hp='255', max_mp='255')
    weapon['item_add_option'].update(all_stat='6', damage='6')
    ring = {'item_name': '샘플 링', 'item_equipment_slot': '반지1', 'item_equipment_part': '반지',
            'item_icon': icon('ring', ''), 'starforce': '22', 'scroll_upgrade': '3',
            'item_base_option': {'base_equipment_level': 160, 'str': '10', 'attack_power': '2'},
            'item_total_option': {'str': '85', 'attack_power': '47'},
            'item_starforce_option': {'str': '75', 'attack_power': '45'},
            'potential_option_grade': '레전드리', 'potential_option_1': 'STR +12%',
            'potential_option_2': 'STR +9%', 'potential_option_3': 'STR +9%'}
    symbols = []
    for name, level, force, stat, current, required, color in [
        ('샘플 아케인심볼', 20, '220', '2200', 0, 0, '#63b4db'),
        ('샘플 어센틱심볼', 7, '70', '1100', 123, 456, '#a5a1eb'),
    ]:
        symbols.append({'symbol_name': name, 'symbol_icon': icon('symbol', color),
                        'symbol_level': level, 'symbol_force': force, 'symbol_str': stat,
                        'symbol_growth_count': current, 'symbol_require_growth_count': required})
    raw = {
        Source.EQUIPMENT: {'preset_no': 2, 'item_equipment': [weapon, ring]},
        Source.SYMBOLS: {'symbol': symbols},
        Source.UNION_BASIC: {'union_level': 9000, 'union_grade': '그랜드 마스터 유니온', 'union_artifact_level': 40},
        Source.UNION_RAIDER: {'union_block': [
            {'block_class': '히어로', 'block_level': '250', 'block_position': [{'x': -2, 'y': 1}, {'x': -1, 'y': 1}, {'x': 0, 'y': 1}, {'x': 0, 'y': 2}]},
            {'block_class': '아델', 'block_level': '280', 'block_position': [{'x': 1, 'y': 0}, {'x': 2, 'y': 0}, {'x': 2, 'y': -1}, {'x': 2, 'y': -2}]},
            {'block_class': '팬텀', 'block_level': '250', 'block_position': [{'x': -2, 'y': -1}, {'x': -1, 'y': -1}, {'x': -1, 'y': -2}, {'x': 0, 'y': -2}]},
        ], 'union_raider_stat': ['STR +40', '공격력 +20'], 'union_occupied_stat': ['보스 몬스터 공격 시 데미지 +40%']},
    }
    character = CharacterSheet('synthetic-frontend-demo', {
        source: Document.parse(source, json.dumps(body, ensure_ascii=False)) for source, body in raw.items()
    }).as_character()
    return character.to_view()


if __name__ == '__main__':
    target = ROOT / 'docs/examples/view-data.js'
    target.write_text('// Generated by tools/build_frontend_example.py; synthetic data, original sample icons.\n'
                      + 'window.MAPLE_DEMO_VIEW = ' + json.dumps(build(), ensure_ascii=False, indent=2) + ';\n')
    print('Generated docs/examples/view-data.js through Character.to_view()')
